   ! colormap `name` (one of CMAP_NAMES) at t in [0,1] -> r, g, b in [0,1].
   ! unknown names fall back to teal.
   pure subroutine cmap_rgb(name, t, r, g, b)
      character(len=*), intent(in) :: name
      real(real64), intent(in) :: t
      real(real64), intent(out) :: r, g, b
      real(real64) :: x
      x = min(max(t, 0.d0), 1.d0)
      select case (name)
      case ('blue')                         ! the exact epsnuc gain ramp
         r = 1.d0 - 0.85d0*x; g = r; b = 1.d0
      case ('gray')
         r = 1.d0 - x; g = r; b = r
      case ('viridis')
         call interp(VIRIDIS, x, r, g, b)
      case ('plasma')
         call interp(PLASMA, x, r, g, b)
      case ('inferno')
         call interp(INFERNO, x, r, g, b)
      case ('magma')
         call interp(MAGMA, x, r, g, b)
      case ('cividis')
         call interp(CIVIDIS, x, r, g, b)
      case ('Greys')
         call interp(GREYS, x, r, g, b)
      case ('Blues')
         call interp(BLUES, x, r, g, b)
      case ('Greens')
         call interp(GREENS, x, r, g, b)
      case ('Reds')
         call interp(REDS, x, r, g, b)
      case ('Purples')
         call interp(PURPLES, x, r, g, b)
      case ('Oranges')
         call interp(ORANGES, x, r, g, b)
      case ('coolwarm')
         call interp(COOLWARM, x, r, g, b)
      case ('RdBu')
         call interp(RDBU, x, r, g, b)
      case ('turbo')
         call interp(TURBO, x, r, g, b)
      case default                          ! 'teal': white -> teal-blue
         r = 1.d0 + x*(0.09d0 - 1.d0)
         g = 1.d0 + x*(0.42d0 - 1.d0)
         b = 1.d0 + x*(0.67d0 - 1.d0)
      end select
   end subroutine cmap_rgb

   pure subroutine interp(tab, x, r, g, b)
      real(real64), intent(in) :: tab(3, NANCHOR), x
      real(real64), intent(out) :: r, g, b
      real(real64) :: xx, u
      integer(int32) :: k
      xx = x*real(NANCHOR - 1, real64)
      k = min(int(xx) + 1, NANCHOR - 1)
      u = xx - real(k - 1, real64)
      r = tab(1, k) + u*(tab(1, k + 1) - tab(1, k))
      g = tab(2, k) + u*(tab(2, k + 1) - tab(2, k))
      b = tab(3, k) + u*(tab(3, k + 1) - tab(3, k))
   end subroutine interp

end module cmaps
